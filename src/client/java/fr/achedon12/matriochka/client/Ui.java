package fr.achedon12.matriochka.client;

import fr.achedon12.matriochka.Matriochka;
import java.util.ArrayList;
import java.util.List;
import java.util.function.BooleanSupplier;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.Font;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.client.renderer.RenderPipelines;
import net.minecraft.network.chat.Component;
import net.minecraft.sounds.SoundEvents;

/**
 * Matryoshka folk-art kit: a nested lacquer frame (black, red, gold), birch paper, painted drawers, ribbons and
 * lacquered buttons. All sprites are nine-slice textures generated by tools/gui.py.
 */
public final class Ui {
	public static final int INK = 0xFF3A2416, INK_SOFT = 0xFF7A5A40, GOLD = 0xFFE8C060, GOLD_DARK = 0xFF96682A,
		PAPER_TEXT = 0xFF3A2416, LIGHT = 0xFFF4E6C8, RED = 0xFFB3261E, GREEN = 0xFF4F7A3A, MUTED = 0xFFB8A488;

	private Ui() {}

	public static void sprite(GuiGraphicsExtractor g, String name, int x, int y, int w, int h) {
		g.blitSprite(RenderPipelines.GUI_TEXTURED, Matriochka.id(name), x, y, w, h);
	}

	public static void frame(GuiGraphicsExtractor g, int x, int y, int w, int h) {
		sprite(g, "frame", x, y, w, h);
	}

	public static void paper(GuiGraphicsExtractor g, int x, int y, int w, int h) {
		sprite(g, "paper", x, y, w, h);
	}

	/** A title in the lacquer band, centred, scaled 1.25x with a gold drop. */
	public static void title(GuiGraphicsExtractor g, Font font, Component text, int cx, int y) {
		g.pose().pushMatrix();
		g.pose().translate(cx, y);
		g.pose().scale(1.25f, 1.25f);
		int w = font.width(text);
		g.text(font, text, -w / 2 + 1, 1, 0xFF1E1410, false);
		g.text(font, text, -w / 2, 0, GOLD, false);
		g.pose().popMatrix();
	}

	/** A gauge drawn as a gold-rimmed groove with a coloured fill. */
	public static void gauge(GuiGraphicsExtractor g, int x, int y, int w, int h, float frac, int color) {
		g.fill(x, y, x + w, y + h, 0xFF1E1410);
		g.fill(x + 1, y + 1, x + w - 1, y + h - 1, 0xFF4A3426);
		int fw = Math.round((w - 2) * Math.max(0, Math.min(1, frac)));
		g.fill(x + 1, y + 1, x + 1 + fw, y + h - 1, color);
		if (fw > 0) g.fill(x + 1, y + 1, x + 1 + fw, y + 2, 0x55FFFFFF);
		g.outline(x - 1, y - 1, w + 2, h + 2, GOLD_DARK);
	}

	public static int worldColor(int world) {
		return switch (world) {
			case 1 -> 0xFF8FBF3A; case 2 -> 0xFFE07A2A; case 3 -> 0xFF6FB8E0; case 4 -> 0xFFE8C83A; case 5 -> 0xFF5A78E0;
			case 6 -> 0xFFD07AD8; case 7 -> 0xFF3AB8C8; case 8 -> 0xFFD8A040; case 9 -> 0xFFC86A4A; case 10 -> 0xFFE8C060;
			default -> 0xFFB3261E;
		};
	}

	/** Self-drawn lacquer buttons, so the whole interface shares one material. */
	public static final class Buttons {
		private record B(int x, int y, int w, int h, Component label, Runnable action, BooleanSupplier enabled) {}

		private final List<B> list = new ArrayList<>();

		public void clear() {
			list.clear();
		}

		public void add(int x, int y, int w, int h, Component label, Runnable action) {
			list.add(new B(x, y, w, h, label, action, () -> true));
		}

		public void add(int x, int y, int w, int h, Component label, Runnable action, BooleanSupplier enabled) {
			list.add(new B(x, y, w, h, label, action, enabled));
		}

		public void draw(GuiGraphicsExtractor g, Font font, int mx, int my) {
			for (B b : list) {
				boolean on = b.enabled.getAsBoolean();
				boolean hover = on && mx >= b.x && mx < b.x + b.w && my >= b.y && my < b.y + b.h;
				sprite(g, !on ? "button_off" : hover ? "button_hover" : "button", b.x, b.y, b.w, b.h);
				int tw = font.width(b.label);
				g.text(font, b.label, b.x + (b.w - tw) / 2, b.y + (b.h - 8) / 2, on ? LIGHT : 0xFF8A7A70, false);
			}
		}

		public boolean click(double mx, double my) {
			for (B b : list) {
				if (b.enabled.getAsBoolean() && mx >= b.x && mx < b.x + b.w && my >= b.y && my < b.y + b.h) {
					Minecraft.getInstance().getSoundManager().play(net.minecraft.client.resources.sounds.SimpleSoundInstance.forUI(SoundEvents.WOODEN_BUTTON_CLICK_ON, 1.2f));
					b.action.run();
					return true;
				}
			}
			return false;
		}
	}
}
