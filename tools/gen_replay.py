"""Generates the replay content (trials, world events, talents, new gear) from content.py.

Called by gen.py: item_assets() paints and models the replay items, gen() writes their lang entries and the Java
definitions in content/ReplayContent.java.
"""
import os

from content import (TALENTS, TALENT_TIERS, TALENT_REFUND, TALENT_EFFECTS, TALENT_PERCENT, TRIAL_SCALE, TRIAL_MUTATION,
                     TRIALS, TRIAL_SOULS, TRIAL_TITLES, TRIAL_NAMES, INVASION, SURGE, MERCHANT, SURGES, MERCHANTS,
                     REPLAY_GEAR, TRIAL_ALTAR_RECIPE, CLASSES)
import paint_replay

NS = "matriochka"
JAVA = "src/main/java/fr/achedon12/matriochka/content/ReplayContent.java"


def item_assets(it, pal, tpath, write, assets):
    """Paints a replay item and writes its models. False for every other item (gen.py paints those)."""
    shape = it.get("shape", "")
    if shape not in paint_replay.SHAPES:
        return False
    iid = it["id"]
    paint_replay.paint(shape, pal, tpath)
    model = lambda name, parent, tex: write(os.path.join(assets, f"models/item/{name}.json"), {"parent": parent, "textures": {"layer0": f"{NS}:item/{tex}"}})
    if shape == "spore_bow":
        # the vanilla bow's frames: drawn back a little, more, then fully
        model(iid, "minecraft:item/bow", iid)
        for i in range(3):
            model(f"{iid}_pulling_{i}", f"{NS}:item/{iid}", f"{iid}_pulling_{i}")
        frame = lambda i: {"type": "minecraft:model", "model": f"{NS}:item/{iid}_pulling_{i}"}
        write(os.path.join(assets, f"items/{iid}.json"), {"model": {
            "type": "minecraft:condition", "property": "minecraft:using_item",
            "on_false": {"type": "minecraft:model", "model": f"{NS}:item/{iid}"},
            "on_true": {"type": "minecraft:range_dispatch", "property": "minecraft:use_duration", "scale": 0.05,
                        "entries": [{"threshold": 0.65, "model": frame(1)}, {"threshold": 0.9, "model": frame(2)}], "fallback": frame(0)}}})
        return True
    held = it["kind"] in ("weapon", "tool")
    model(iid, "minecraft:item/handheld" if held else "minecraft:item/generated", iid)
    write(os.path.join(assets, f"items/{iid}.json"), {"model": {"type": "minecraft:model", "model": f"{NS}:item/{iid}"}})
    return True


def _shown(effect, value):
    v = value * 100 if effect in TALENT_PERCENT else value
    return str(int(round(v))) if abs(v - round(v)) < 1e-6 else ("%g" % v)


def jstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen(lang, write, root):
    class_names = {c[0]: (c[1], c[2]) for c in CLASSES}
    rows = []
    for cls, branches in TALENTS.items():
        assert len(branches) == 3, cls
        for bid, ben, bfr, talents in branches:
            assert len(talents) == 4, bid
            lang(f"talent.{NS}.branch.{cls}.{bid}", ben, bfr)
            for tier, (tid, en, fr, effect, value) in enumerate(talents):
                full = f"{cls}_{tid}"
                ten, tfr = TALENT_EFFECTS[effect]
                lang(f"talent.{NS}.{full}", en, fr)
                lang(f"talent.{NS}.{full}.desc", ten % _shown(effect, value), tfr % _shown(effect, value))
                souls, shards, gate = TALENT_TIERS[tier]
                rows.append(f"\t\tnew TalentDef({jstr(full)}, {jstr(cls)}, {jstr(bid)}, {tier}, {jstr(effect)}, {value}f, {souls}, {shards}, {gate})")
    for key, (en, fr) in TRIAL_NAMES.items():
        lang(f"trial.{NS}.{key}", en, fr)
    for key, (tid, en, fr) in TRIAL_TITLES.items():
        lang(f"title.{NS}.{tid}", en, fr)
    for w, (sid, en, fr, den, dfr) in SURGES.items():
        lang(f"event.{NS}.surge.{w}", en, fr)
        lang(f"event.{NS}.surge.{w}.desc", den, dfr)
    for w, ((en, fr), _trades) in MERCHANTS.items():
        lang(f"event.{NS}.merchant.{w}", en, fr)

    L = ["package fr.achedon12.matriochka.content;", "", "import java.util.List;", "",
         "/** GENERATED by tools/gen_replay.py from tools/content.py: trials, world events, talents and the new gear. Do not edit by hand. */",
         "public final class ReplayContent {", "\tprivate ReplayContent() {}", "",
         "\t/** A talent: its class and branch, its tier (0..3) in the branch, its effect and value, what it costs and the highest boss it needs. */",
         "\tpublic record TalentDef(String id, String cls, String branch, int tier, String effect, float value, int souls, int shards, int gate) {}",
         "\t/** A trial: its key, its world (0 for the Gauntlet) and its par time in seconds. */",
         "\tpublic record TrialDef(String key, int world, int par, String title) {}",
         "\t/** A station recipe of the replay gear (ids without namespace are Matriochka items). */",
         "\tpublic record GearRecipe(String station, String output, int requires, List<String> inputs, List<Integer> counts) {}",
         "\tpublic record Trade(String cost, int costCount, String result, int resultCount) {}", ""]
    L.append("\tpublic static final List<TalentDef> TALENTS = List.of(\n" + ",\n".join(rows) + "\n\t);")
    L.append("\t/** The classes in the order of their talent trees. */")
    L.append("\tpublic static final String[] CLASSES = {" + ", ".join(jstr(c) for c in TALENTS) + "};")
    L.append(f"\tpublic static final float TALENT_REFUND = {TALENT_REFUND}f;")
    s = TRIAL_SCALE
    L.append(f"\tpublic static final float TRIAL_HEALTH = {s['health']}f, TRIAL_DAMAGE = {s['damage']}f, GAUNTLET_HEALTH = {s['gauntlet_health']}f, GAUNTLET_DAMAGE = {s['gauntlet_damage']}f;")
    L.append(f"\tpublic static final int TRIAL_WAVE = {s['wave']}, TRIAL_ELITES = {s['elites']}, TRIAL_SOULS = {TRIAL_SOULS};")
    L.append("\t/** The mutation each boss wakes with in a trial, by world (0 is the Block Guardian). */")
    L.append("\tpublic static final String[] TRIAL_MUTATION = {" + ", ".join(jstr(TRIAL_MUTATION[w]) for w in range(11)) + "};")
    L.append("\tpublic static final List<TrialDef> TRIALS = List.of(\n" + ",\n".join(
        f"\t\tnew TrialDef({jstr(k)}, {w}, {par}, {jstr(TRIAL_TITLES[k][0])})" for (k, w, par) in TRIALS) + "\n\t);")
    L.append(f"\tpublic static final String SWIFT_TITLE = {jstr(TRIAL_TITLES['swift'][0])};")
    i = INVASION
    L.append(f"\tpublic static final int INVASION_WARNING = {i['warning']}, INVASION_WAVES = {i['waves']}, INVASION_BASE = {i['base']}, INVASION_PER_PLAYER = {i['per_player']}, INVASION_TIME = {i['time']};")
    L.append(f"\tpublic static final float WARLORD_HEALTH = {i['warlord_health']}f, WARLORD_DAMAGE = {i['warlord_damage']}f;")
    L.append(f"\tpublic static final int SURGE_WARNING = {SURGE['warning']}, SURGE_DURATION = {SURGE['duration']}, SURGE_SOULS = {SURGE['souls']};")
    L.append(f"\tpublic static final float SURGE_STRENGTH = {SURGE['strength']}f;")
    L.append(f"\tpublic static final int MERCHANT_STAY = {MERCHANT['stay']};")
    L.append("\t/** The surge of each world, by world number (index 0 unused). */")
    L.append("\tpublic static final String[] SURGES = {\"\", " + ", ".join(jstr(SURGES[w][0]) for w in range(1, 11)) + "};")
    trade_rows = []
    for w in range(1, 11):
        trades = MERCHANTS[w][1]
        trade_rows.append("\t\tList.of(" + ", ".join(f"new Trade({jstr(c)}, {cn}, {jstr(r)}, {rn})" for (c, cn, r, rn) in trades) + ")")
    L.append("\t/** The travelling merchant's special trades, by world number (index 0 unused). */")
    L.append("\tpublic static final List<List<Trade>> MERCHANT_TRADES = List.of(List.of(),\n" + ",\n".join(trade_rows) + "\n\t);")
    rec = []
    for g in REPLAY_GEAR:
        station, ings = g[9], g[10]
        rec.append(f"\t\tnew GearRecipe({jstr(station)}, {jstr(g[0])}, -1, List.of(" + ", ".join(jstr(a) for a, _ in ings) + "), List.of(" + ", ".join(str(n) for _, n in ings) + "))")
    st, req, ings = TRIAL_ALTAR_RECIPE
    rec.append(f"\t\tnew GearRecipe({jstr(st)}, \"trial_altar\", {req}, List.of(" + ", ".join(jstr(a) for a, _ in ings) + "), List.of(" + ", ".join(str(n) for _, n in ings) + "))")
    L.append("\tpublic static final List<GearRecipe> RECIPES = List.of(\n" + ",\n".join(rec) + "\n\t);")
    L.append("\t/** Ids of the replay gear, whose behaviour lives in item/ReplayGear. */")
    L.append("\tpublic static final List<String> GEAR = List.of(" + ", ".join(jstr(g[0]) for g in REPLAY_GEAR) + ");")
    L.append("}")
    write(os.path.join(root, JAVA), "\n".join(L) + "\n")
    return len(rows)
